#!/usr/bin/env python3
"""
This builds mjcf/lab_objects.xml, the lab scene's samples, from config/lab/lab.yaml. A sample
gets one MuJoCo body for every look it can have in its protocol (its visual twins), because a
body cannot be recoloured while MuJoCo runs; cell_lab shows a sample by moving the right twin
into its place and parking the others. Every twin starts parked on the floor under the table,
out of the camera's view, and cell_lab sets the samples out when it starts or resets. A twin's
body and free joint are both named <sample>__<look>, so the free-joint publisher reports each
one under that name. A look with a colony (the growth experiment's dishes) also gets a thin disc
on its top face, visual only. Run it with python3 build_lab_mjcf.py after editing lab.yaml.
"""
import argparse
import math
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parents[1]
CONFIG = PKG / "config" / "lab" / "lab.yaml"
OUT = PKG / "mjcf" / "lab_objects.xml"


def fmt(*values):
    return " ".join(f"{v:.6f}".rstrip("0").rstrip(".") if v != 0 else "0" for v in values)


def twins(cfg):
    """[(sample, look)] for every sample and every look its protocol has, in file order."""
    out = []
    for protocol in cfg["protocols"].values():
        looks = protocol["looks"]
        looks = list(looks.values()) if isinstance(looks, dict) else list(looks)
        for sample in protocol["samples"]:
            out += [(sample, look) for look in looks]
    return out


def parking_spots(parking, count):
    """count (x, y) spots on the floor grid, row by row, or an error if the grid is too small."""
    (x0, x1), (y0, y1), pitch = parking["x"], parking["y"], parking["pitch"]
    xs = [x0 + i * pitch for i in range(int(math.floor((x1 - x0) / pitch)) + 1)]
    ys = [y0 + j * pitch for j in range(int(math.floor((y1 - y0) / pitch)) + 1)]
    spots = [(x, y) for x in xs for y in ys]
    if len(spots) < count:
        raise ValueError(f"parking grid has {len(spots)} spots for {count} twins")
    return spots[:count]


def main():
    ap = argparse.ArgumentParser(description="Generate the lab samples' MJCF from lab.yaml.")
    ap.add_argument("--config", type=Path, default=CONFIG)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    config, out = args.config.resolve(), args.out.resolve()
    cfg = yaml.safe_load(config.read_text())
    types = cfg["types"]
    pairs = twins(cfg)
    floor = cfg["parking"]["floor"]

    # only the looks have colours; the generic types (tube, dish) are for the detector
    materials = [f'    <material name="lab_{name}" rgba="{fmt(*t["rgba"])}"/>'
                 for name, t in types.items() if "rgba" in t]
    for name, t in types.items():
        if "colony" in t:
            materials.append(
                f'    <material name="lab_{name}_colony" rgba="{fmt(*t["colony"]["rgba"])}"/>')
    bodies = []
    for (sample, look), (x, y) in zip(pairs, parking_spots(cfg["parking"], len(pairs))):
        t = types[look]
        sx, sy, sz = t["size"]
        if t["shape"] != "cylinder":
            raise ValueError(f"{sample}: lab samples are cylinders, {look} is {t['shape']}")
        name = f"{sample}__{look}"
        geoms = [f'      <geom class="lab_sample" type="cylinder" size="{fmt(sx / 2, sz / 2)}" '
                 f'material="lab_{look}"/>']
        if "colony" in t:
            # a 1 mm disc on the dish's top face, there to be seen: it takes part in no contact
            r = t["colony"]["radius"]
            geoms.append(f'      <geom type="cylinder" pos="0 0 {fmt(sz / 2 + 0.0005)}" '
                         f'size="{fmt(r, 0.0005)}" contype="0" conaffinity="0" mass="0" '
                         f'material="lab_{look}_colony"/>')
        bodies += [f'    <body name="{name}" pos="{fmt(x, y, floor + sz / 2)}">',
                   f'      <freejoint name="{name}"/>', *geoms, "    </body>"]
    xml = "\n".join([
        "<!-- GENERATED by cell_description/scripts/build_lab_mjcf.py from "
        f"{config.relative_to(PKG)}. Do not edit by hand. -->",
        '<mujoco model="lab_objects">',
        "  <default>",
        '    <default class="lab_sample">',
        '      <geom condim="4" friction="1 0.01 0.001" solref="0.005 1" density="800"/>',
        "    </default>",
        "  </default>",
        "  <asset>", *materials, "  </asset>",
        "  <worldbody>", *bodies, "  </worldbody>",
        "</mujoco>", "",
    ])
    out.write_text(xml)
    print(f"wrote {out}: {len(pairs)} twins for {len({s for s, _ in pairs})} samples")


if __name__ == "__main__":
    main()
