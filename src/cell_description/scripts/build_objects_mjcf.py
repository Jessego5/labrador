#!/usr/bin/env python3
"""
This builds mjcf/objects.xml, the free-floating objects in the scene, from config/objects.yaml,
placing each instance at its default start pose resting on the table. Each object is a body
with a free joint named like the object, so the MuJoCo free-joint publisher reports its ground
truth pose under that name, which is what the benchmarks score against and what moves an object
to a randomised start. Run it with python3 build_objects_mjcf.py after editing objects.yaml.
"""
import math
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parents[1]
CONFIG = PKG / "config" / "objects.yaml"
OUT = PKG / "mjcf" / "objects.xml"


def fmt(*values):
    return " ".join(f"{v:.6f}".rstrip("0").rstrip(".") if v != 0 else "0" for v in values)


def main():
    cfg = yaml.safe_load(CONFIG.read_text())
    types = cfg["types"]
    materials = [f'    <material name="obj_{name}" rgba="{fmt(*t["rgba"])}"/>' for name, t in types.items()]
    bodies = []
    for name, obj in cfg["objects"].items():
        t = types[obj["type"]]
        sx, sy, sz = t["size"]
        x, y, yaw = obj["pose"]
        if t["shape"] == "box":
            geom = f'type="box" size="{fmt(sx / 2, sy / 2, sz / 2)}"'
        elif t["shape"] == "cylinder":
            geom = f'type="cylinder" size="{fmt(sx / 2, sz / 2)}"'
        else:
            raise ValueError(f"{name}: unknown shape {t['shape']!r}")
        quat = fmt(math.cos(yaw / 2), 0, 0, math.sin(yaw / 2))
        bodies += [
            f'    <body name="{name}" pos="{fmt(x, y, sz / 2)}" quat="{quat}">',
            f'      <freejoint name="{name}"/>',
            f'      <geom class="object" {geom} material="obj_{obj["type"]}"/>',
            "    </body>",
        ]
    xml = "\n".join([
        "<!-- GENERATED by cell_description/scripts/build_objects_mjcf.py from config/objects.yaml. "
        "Do not edit by hand. -->",
        '<mujoco model="objects">',
        "  <default>",
        '    <default class="object">',
        '      <geom condim="4" friction="1 0.01 0.001" solref="0.005 1" density="800"/>',
        "    </default>",
        "  </default>",
        "  <asset>", *materials, "  </asset>",
        "  <worldbody>", *bodies, "  </worldbody>",
        "</mujoco>", "",
    ])
    OUT.write_text(xml)
    print(f"wrote {OUT}: {len(cfg['objects'])} objects")


if __name__ == "__main__":
    main()
